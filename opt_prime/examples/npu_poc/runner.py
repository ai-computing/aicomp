"""Execution — plug the compiled stages into the model and run it.  Integration item #3.

Reuses the biggest strength found in the ATOM PoC:

    Replace split_gm.submod_k with an NPU wrapper and the top-level forward
    generated by FX becomes the pipeline as-is.  Not a single line of stage
    wiring is written — fan-out such as rotary cos/sin produced in stage 0
    and consumed in stages 2 and 3 is handled automatically.

This is the largest integration item.  The engine runs PP as one process per
rank + send/recv (schedule.py), whereas on an NPU the device is an argument,
so a single process iterating over all stages is the natural fit.  The two
models conflict directly, so integration is not a simple port but a redesign
of the execution model.  To avoid deferring that choice, the latter is
implemented explicitly here.

Note: this PoC actually chains the stages — each stage's NPU output becomes the
  next stage's input.  The cross-version harness fed each stage its own real
  CPU inputs, so errors did not accumulate.  Here they do — so the numbers can
  be worse, and that is the true value of the pipeline.

Micro-batch pipelining (AsyncRuntime) is implemented below.
"""

from __future__ import annotations

import time

import torch
import torch.nn as nn

from .stage_io import BoundarySpec


class NpuStageWrapper(nn.Module):
    """Module placed in the `split_gm.submod_k` slot.  Delegates forward to the NPU."""

    def __init__(self, stage, spec: BoundarySpec):
        super().__init__()
        self.stage = stage
        self.single_output = spec.out_kind == "single"
        # Scalars were baked into the binary at compile time.  The FX-generated
        # caller still passes them, so filter them here and re-insert on output.
        self.out_consts = dict(spec.out_consts)
        self.n_calls = 0
        self.total_ms = 0.0

    def forward(self, *args):
        tensors = tuple(a for a in args if isinstance(a, torch.Tensor))
        t0 = time.time()
        out = self.stage.run(*tensors)
        self.total_ms += (time.time() - t0) * 1000
        self.n_calls += 1

        if self.out_consts:
            vals = list(out) if isinstance(out, (list, tuple)) else [out]
            for pos, v in sorted(self.out_consts.items()):
                vals.insert(pos, v)
            return vals
        # For runtimes that return a list for multiple outputs and a Tensor for
        # a single one — preserve exactly the shape the consuming FX code expects.
        if self.single_output and isinstance(out, (list, tuple)):
            return out[0]
        if (not self.single_output) and not isinstance(out, (list, tuple)):
            return [out]
        return out


def attach(split_gm, compiled: dict, specs: dict[str, BoundarySpec]) -> dict:
    """Replace stages with NPU wrappers.  Returns the wrapper dict (for instrumentation)."""
    wrappers = {}
    for name, stage in compiled.items():
        w = NpuStageWrapper(stage, specs[name])
        setattr(split_gm, name, w)
        wrappers[name] = w
    return wrappers


def run(split_gm, driver_inputs: dict, repeat: int = 3):
    """Run the pipeline.  Reports the minimum time and also returns the range.

    On a shared machine timings fluctuate with contention — verdicts are
    robust, milliseconds are not.  So measure several times and report the range.
    """
    global last_repeat_identical
    args = list(driver_inputs.values())
    times = []
    out = first = None
    same = True
    with torch.no_grad():
        for _ in range(max(1, repeat)):
            t0 = time.time()
            out = split_gm(*args)
            times.append((time.time() - t0) * 1000)
            flat = _leaves(out)
            if first is None:
                first = [t.detach().cpu().clone() for t in flat]
            else:
                same = same and len(flat) == len(first) and all(
                    torch.equal(a.detach().cpu(), b) for a, b in zip(flat, first))
    last_repeat_identical = same
    return out, min(times), max(times), times


# Whether every run of the last runner.run() call gave bit-identical outputs.
last_repeat_identical = True


def _leaves(x) -> list:
    if isinstance(x, torch.Tensor):
        return [x]
    if isinstance(x, (list, tuple)):
        return [t for v in x for t in _leaves(v)]
    if isinstance(x, dict):
        return [t for v in x.values() for t in _leaves(v)]
    return []


def stage_times(wrappers: dict) -> str:
    return " · ".join(
        f"{n}={w.total_ms / max(w.n_calls, 1):.1f}ms"
        for n, w in wrappers.items())



# ─────────────────────────────────────────────────────────────────────
# Micro-batch pipelining — throughput
# ─────────────────────────────────────────────────────────────────────
#
# The real value of PP is throughput, not latency.  Run serially, stage times
# simply add up (measured: serial PP=4 is slower than PP=1), but streaming M
# requests brings steady-state throughput close to **1/max(t_stage)** rather
# than 1/Σt.
#
# The previous PoC kept this PP=2-only — it assumed a simple chain where
# stage 1 consumes only stage 0's output, which breaks on Llama PP=4 because
# rotary cos/sin form a skip edge from stage 0 to stages 2 and 3.
#
# Here dependencies are read directly from the top-level FX graph, generalizing
# to arbitrary PP.  This is also exactly what integration item #3 needs — the
# engine must have an explicit scheduler instead of the FX forward.


def build_dag(split_gm, stage_names: list[str]) -> dict:
    """Read inter-stage dependencies from the top-level split graph.

    Each stage input is described as one of:
        ("input", placeholder_name)            comes from the driver inputs
        ("stage", (source_stage, output_index))  comes from an earlier stage

    Returns: {stage_name: [dep, ...]}  — preserves argument order.
    """
    name_set = set(stage_names)
    # getitem node → (source stage, index)
    getitem_src: dict[str, tuple[str, int]] = {}
    for n in split_gm.graph.nodes:
        if n.op == "call_function" and n.target.__name__ == "getitem":
            src, idx = n.args
            if getattr(src, "op", None) == "call_module" and src.target in name_set:
                getitem_src[n.name] = (src.target, idx)

    dag: dict[str, list] = {}
    for n in split_gm.graph.nodes:
        if n.op != "call_module" or n.target not in name_set:
            continue
        deps = []
        for a in n.args:
            if getattr(a, "op", None) == "placeholder":
                deps.append(("input", a.target))
            elif getattr(a, "name", None) in getitem_src:
                deps.append(("stage", getitem_src[a.name]))
            elif getattr(a, "op", None) == "call_module" and a.target in name_set:
                # single-output stages are referenced directly without getitem
                deps.append(("stage", (a.target, 0)))
            else:
                raise SystemExit(f"[runner] cannot resolve argument {a} of "
                                 f"{n.target} — the micro-batch scheduler "
                                 f"cannot read its dependencies")
        dag[n.target] = deps
    return dag


def _as_list(out):
    return list(out) if isinstance(out, (list, tuple)) else [out]


def _ensure(done: dict, handles: dict, key):
    """Wait for a result only when it is actually needed.

    This is the key to overlap.  Waiting for all M results of stage k before
    submitting stage k+1 leaves the two devices idling in turn and gives a
    1.00× speedup (measured).  Waiting only for the m-th result and handing it
    straight to the next stage lets the earlier stage keep processing m+1...
    """
    if key not in done:
        done[key] = _as_list(handles[key].wait())
    return done[key]


def _gather(deps, micro_inputs: dict, done: dict, m: int, handles: dict | None = None):
    """Collect one stage's input tensors.  Scalars are baked into the binary."""
    args = []
    for kind, ref in deps:
        if kind == "input":
            args.append(micro_inputs[ref][m])
        else:
            src, idx = ref
            vals = (_ensure(done, handles, (src, m)) if handles is not None
                    else done[(src, m)])
            args.append(vals[idx])
    return [a for a in args if isinstance(a, torch.Tensor)]


def pipelined(compiled: dict, specs, stage_names: list[str], dag: dict,
              micro_inputs: dict, n_micro: int):
    """Pipelined run — submit M micro-batches asynchronously, stage by stage.

    While stage k's submissions sit in its queue, stage k+1 starts as soon as
    (k, 0) completes, so in steady state both devices are busy at once.
    A skip edge simply holds on to the earlier stage's output until used.
    """
    t0 = time.time()
    handles: dict = {}
    done: dict = {}

    for name in stage_names:                      # the outer loop over stages is the key
        stage = compiled[name]
        for m in range(n_micro):
            # Wait only for the m-th result of the earlier stage — m+1... keep
            # running on that device.  This is the overlap.
            args = _gather(dag[name], micro_inputs, done, m, handles)
            h = stage.run_async(*args)
            if h is None:
                raise SystemExit(f"[runner] {stage} does not support async "
                                 f"submission — check backend caps.supports_async")
            handles[(name, m)] = h

    last = stage_names[-1]
    outs = [_ensure(done, handles, (last, m))[0] for m in range(n_micro)]
    return outs, (time.time() - t0) * 1000


def serial(compiled: dict, specs, stage_names: list[str], dag: dict,
           micro_inputs: dict, n_micro: int):
    """Serial baseline — runs one request end to end at a time with the same binaries.

    Building a separate baseline would break the control; only the runtime is synchronous.
    """
    t0 = time.time()
    outs = []
    for m in range(n_micro):
        done: dict = {}
        for name in stage_names:
            args = _gather(dag[name], micro_inputs, done, m)
            done[(name, m)] = _as_list(compiled[name].run(*args))
        outs.append(done[(stage_names[-1], m)][0])
    return outs, (time.time() - t0) * 1000
